package py.edu.une.politecnica.robogest.dto;

import java.io.Serializable;

/**
 * DTO para la creacion y actualizacion de materiales en el inventario.
 */
public class MaterialRequestDTO implements Serializable {

    private static final long serialVersionUID = 1L;

    private Long categoriaId;
    private String nombre;
    private String descripcion;
    private String marca;
    private String modelo;
    private Integer cantidadTotal;
    private String estado; // ACTIVO, MANTENIMIENTO, BAJA
    private String ubicacion;

    public MaterialRequestDTO() {
    }

    public Long getCategoriaId() {
        return categoriaId;
    }

    public void setCategoriaId(Long categoriaId) {
        this.categoriaId = categoriaId;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getDescripcion() {
        return descripcion;
    }

    public void setDescripcion(String descripcion) {
        this.descripcion = descripcion;
    }

    public String getMarca() {
        return marca;
    }

    public void setMarca(String marca) {
        this.marca = marca;
    }

    public String getModelo() {
        return modelo;
    }

    public void setModelo(String modelo) {
        this.modelo = modelo;
    }

    public Integer getCantidadTotal() {
        return cantidadTotal;
    }

    public void setCantidadTotal(Integer cantidadTotal) {
        this.cantidadTotal = cantidadTotal;
    }

    public String getEstado() {
        return estado;
    }

    public void setEstado(String estado) {
        this.estado = estado;
    }

    public String getUbicacion() {
        return ubicacion;
    }

    public void setUbicacion(String ubicacion) {
        this.ubicacion = ubicacion;
    }
}
